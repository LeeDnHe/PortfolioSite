export type GamePlatform = 'PC' | '모바일';

/** "이전 버전" 탭의 패치노트 한 건 */
export interface GameVersionNote {
  version: string;
  date: string;
  title: string;
  changes: string[];
  current?: boolean;
}

/** 속성 창(일반/자세히/이전 버전)에 표시할 상세 정보 */
export interface GameDetails {
  github?: string;
  /** 일반 탭 — 항목: 값 형태의 기본 정보 */
  facts: { label: string; value: string }[];
  /** 일반 탭 — 전시·수상 경력 */
  awards: string[];
  /** 자세히 탭 — 만들게 된 배경 (문단 단위) */
  background: string[];
  /** 자세히 탭 — 이 게임으로 보여주고 싶은 것 (문단 단위) */
  statement: string[];
  /** 자세히 탭 맨 끝 — 개발자 코멘트 (문단 단위) */
  devComment?: string[];
  /** 이전 버전 탭 — 최신순 패치노트 */
  versions: GameVersionNote[];
}

export interface GameEntry {
  /** 폴더명이자 URL 경로 조각 */
  id: string;
  title: string;
  tagline: string;
  description: string;
  platform: GamePlatform;
  /** 바탕화면/타이틀바에 표시할 아이콘 이미지 URL */
  icon: string;
  /** 실제 게임이 배포된 주소. 비어 있으면 "개발 중" 처리 */
  playUrl: string;
  /** 모바일 게임 설치 파일 경로(public/ 기준). 있으면 "다운로드" 버튼 표시 */
  downloadUrl?: string;
  /** 유튜브 소개·하이라이트 영상 */
  youtube?: { url: string; label: string };
  year: string;
  /** 없으면 자세히/이전 버전 탭에 준비 중 문구 표시 */
  details?: GameDetails;
}

